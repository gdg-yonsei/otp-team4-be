// Dispatcher hands a generation job to the external AI agent server.
type Dispatcher interface{ Dispatch(jobID string) }

type Handler struct {
	cfg   config.Config
	wikis *service.WikiService
	chats *service.ChatService
	pages *service.PageService
	jobs  *service.GenerationService
	agent Dispatcher
}

func New(cfg config.Config, wikis *service.WikiService, chats *service.ChatService,
	pages *service.PageService, jobs *service.GenerationService, agent Dispatcher) *Handler {
	return &Handler{cfg: cfg, wikis: wikis, chats: chats, pages: pages, jobs: jobs, agent: agent}
}

func (h *Handler) Router() *gin.Engine {
	r := gin.New()
	r.Use(gin.Logger(), gin.Recovery(), middleware.CORS(h.cfg.AllowedOrigins))
	// General per-IP limit; the AI agent is exempt because it makes many page calls.
	general := middleware.RateLimit(rate.Limit(20), 60, middleware.ByIP)
	r.Use(func(c *gin.Context) {
		if middleware.IsAgent(c, h.cfg.AgentToken) {
			c.Next()
			return
		}
		general(c)
	})
	r.MaxMultipartMemory = 8 << 20

	r.GET("/healthz", func(c *gin.Context) { c.Status(http.StatusNoContent) })

	// Swagger UI: /swagger/index.html (OpenAPI JSON: /swagger/doc.json)
	r.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))

	r.POST("/wikis", middleware.RateLimit(rate.Every(time.Minute/10), 10, middleware.ByIP), h.createWiki)

	load := middleware.LoadWiki(h.wikis)
	// Unlock is reachable without a session; 5 attempts/minute per IP+wiki against brute force.
	r.POST("/wikis/:wikiId/unlock",
		middleware.RateLimit(rate.Every(12*time.Second), 5, middleware.ByIPAndWiki), load, h.unlock)

	w := r.Group("/wikis/:wikiId", load, middleware.RequireAccess(h.wikis, h.cfg.AgentToken))
	{
		w.GET("", h.getWiki)
		w.PATCH("", h.updateWiki)

		w.POST("/chats", h.uploadChat)
		w.GET("/chats", h.listChats)

		w.POST("/generations",
			middleware.RateLimit(rate.Every(time.Minute), 5, middleware.ByIPAndWiki), h.createGeneration)
		w.GET("/generations/:jobId", h.getGeneration)
		// Called by the AI agent to report progress/results.
		w.PATCH("/generations/:jobId", middleware.RequireAgent(h.cfg.AgentToken), h.reportGeneration)

		w.GET("/pages", h.listPages)
		w.POST("/pages", h.createPage)
		w.GET("/pages/:pageId", h.getPage)
		w.PATCH("/pages/:pageId", h.updatePage)
		w.DELETE("/pages/:pageId", h.deletePage)
	}

	r.NoRoute(func(c *gin.Context) {
		c.JSON(http.StatusNotFound, apperr.New(http.StatusNotFound, "NOT_FOUND", "요청한 경로를 찾을 수 없습니다."))
	})
	return r
}

func bindJSON(c *gin.Context, v any) bool {
	if err := c.ShouldBindJSON(v); err != nil {
		middleware.Abort(c, apperr.BadRequest("요청 본문이 올바르지 않습니다: "+err.Error()))
		return false
	}
	return true
}

func (h *Handler) setSessionCookie(c *gin.Context, wikiID, token string, exp time.Time) {
	http.SetCookie(c.Writer, &http.Cookie{
		Name:     middleware.SessionCookieName(wikiID),
		Value:    token,
		Path:     "/",
		Expires:  exp,
		MaxAge:   int(time.Until(exp).Seconds()),
		HttpOnly: true,
		Secure:   h.cfg.CookieSecure,
		SameSite: http.SameSiteLaxMode,
	})
}

