//
//	@Summary		AI 문서 생성 요청
//	@Description	작업을 만들고 AI 에이전트 서버로 전달한다(비동기). 위키당 진행 중인 작업은 하나만 허용.
//	@Description	REGENERATE는 AI가 만들고 사람이 수정하지 않은 문서를 먼저 지운다.
