// uploadChat godoc
//
//	@Summary		대화 파일 업로드
//	@Description	카카오톡 "대화 내보내기" TXT 파일 (PC / Android / iOS).
//	@Tags			chats
//	@Accept			multipart/form-data
//	@Produce		json
//	@Param			wikiId	path		string	true	"위키 ID (UUID)"
//	@Param			file	formData	file	true	"카카오톡 대화 TXT"
//	@Success		201		{object}	ChatResponse
//	@Failure		400		{object}	apperr.Error	"INVALID_CHAT_FILE"
//	@Failure		401		{object}	apperr.Error	"WIKI_LOCKED"
//	@Failure		413		{object}	apperr.Error	"FILE_TOO_LARGE"
//	@Security		AgentToken
//	@Router			/wikis/{wikiId}/chats [post]
func (h *Handler) uploadChat(c *gin.Context) {
	const multipartOverhead = 1 << 20
	c.Request.Body = http.MaxBytesReader(c.Writer, c.Request.Body, h.cfg.MaxUploadBytes+multipartOverhead)

	fh, err := c.FormFile("file")
	if err != nil {
		var mbe *http.MaxBytesError
		if errors.As(err, &mbe) {
			middleware.Abort(c, apperr.ErrFileTooLarge)
			return
		}
		middleware.Abort(c, apperr.BadRequest("file 필드에 TXT 파일을 첨부해 주세요."))
		return
	}
	if fh.Size > h.cfg.MaxUploadBytes {
		middleware.Abort(c, apperr.ErrFileTooLarge)
		return
	}
	f, err := fh.Open()
	if err != nil {
		middleware.Abort(c, err)
		return
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, h.cfg.MaxUploadBytes+1))
	if err != nil {
		middleware.Abort(c, err)
		return
	}

	chat, err := h.chats.Upload(c.Request.Context(), middleware.Wiki(c).ID, fh.Filename, data)
	if err != nil {
		middleware.Abort(c, err)
		return
	}
	c.JSON(http.StatusCreated, toChatResponse(chat))
}

