func (h *Handler) wikiResp(w *model.Wiki, withURL bool) WikiResponse {
	r := WikiResponse{ID: w.ID, Name: w.Name, HasPassword: w.HasPassword(), CreatedAt: w.CreatedAt.UTC()}
	if withURL {
		r.URL = h.cfg.PublicBaseURL + "/w/" + w.ID
	}
	return r
}

// createWiki godoc
//
//	@Summary		위키 생성
//	@Description	비밀번호를 주면 비밀번호 위키가 되고, 생성자는 응답과 함께 세션 쿠키를 받는다.
//	@Tags			wikis
//	@Accept			json
//	@Produce		json
//	@Param			body	body		CreateWikiRequest	true	"위키 정보"
//	@Success		201		{object}	WikiResponse
//	@Failure		400		{object}	apperr.Error
//	@Failure		429		{object}	apperr.Error
//	@Router			/wikis [post]
func (h *Handler) createWiki(c *gin.Context) {
	var req CreateWikiRequest
	if !bindJSON(c, &req) {
		return
	}
	w, err := h.wikis.Create(c.Request.Context(), req.Name, req.Password)
	if err != nil {
		middleware.Abort(c, err)
		return
	}
	// The creator gets a session right away so they don't have to unlock their own wiki.
	if w.HasPassword() {
		token, exp, err := h.wikis.IssueSession(c.Request.Context(), w.ID)
		if err != nil {
			middleware.Abort(c, err)
			return
		}
		h.setSessionCookie(c, w.ID, token, exp)
	}
	c.JSON(http.StatusCreated, h.wikiResp(w, true))
}

// unlock godoc
//
//	@Summary		위키 잠금 해제
//	@Description	비밀번호가 맞으면 세션 쿠키(wiki_session_{wikiId}, HttpOnly)를 발급한다. IP+위키당 분당 5회 제한.
//	@Tags			wikis
//	@Accept			json
//	@Param			wikiId	path	string			true	"위키 ID (UUID)"
//	@Param			body	body	UnlockRequest	true	"비밀번호"
//	@Success		204
//	@Failure		403	{object}	apperr.Error	"WIKI_PASSWORD_INVALID"
//	@Failure		404	{object}	apperr.Error	"WIKI_NOT_FOUND"
//	@Failure		429	{object}	apperr.Error
//	@Router			/wikis/{wikiId}/unlock [post]
func (h *Handler) unlock(c *gin.Context) {
	var req UnlockRequest
	if !bindJSON(c, &req) {
		return
	}
	w := middleware.Wiki(c)
	token, exp, err := h.wikis.Unlock(c.Request.Context(), w, req.Password)
	if err != nil {
		middleware.Abort(c, err)
		return
	}
	if token != "" {
		h.setSessionCookie(c, w.ID, token, exp)
	}
	c.Status(http.StatusNoContent)
}

