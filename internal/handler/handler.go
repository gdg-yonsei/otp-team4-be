// updatePage godoc
//
//	@Summary		문서 수정
//	@Description	version 기반 낙관적 잠금. 조회 때 받은 version을 보내야 하며, 그 사이 다른 사람이 수정했으면 409.
//	@Tags			pages
//	@Accept			json
//	@Produce		json
//	@Param			wikiId	path		string				true	"위키 ID (UUID)"
//	@Param			pageId	path		string				true	"문서 ID"
//	@Param			body	body		UpdatePageRequest	true	"변경할 항목 + version"
//	@Success		200		{object}	UpdatePageResponse
//	@Failure		400		{object}	apperr.Error
//	@Failure		401		{object}	apperr.Error	"WIKI_LOCKED"
//	@Failure		404		{object}	apperr.Error	"PAGE_NOT_FOUND"
//	@Failure		409		{object}	apperr.Error	"PAGE_VERSION_CONFLICT / PAGE_TITLE_DUPLICATE"
//	@Security		AgentToken
//	@Router			/wikis/{wikiId}/pages/{pageId} [patch]
func (h *Handler) updatePage(c *gin.Context) {
	var req UpdatePageRequest
	if !bindJSON(c, &req) {
		return
	}
	p, err := h.pages.Update(c.Request.Context(), middleware.Wiki(c).ID, c.Param("pageId"), service.UpdatePageInput{
		Title: req.Title, Category: req.Category, Content: req.Content, Version: req.Version,
	}, middleware.Editor(c))
	if err != nil {
		middleware.Abort(c, err)
		return
	}
	c.JSON(http.StatusOK, UpdatePageResponse{ID: p.ID, Version: p.Version, UpdatedAt: p.UpdatedAt.UTC()})
}

// deletePage godoc
//
//	@Summary	문서 삭제
//	@Tags		pages
//	@Param		wikiId	path	string	true	"위키 ID (UUID)"
//	@Param		pageId	path	string	true	"문서 ID"
//	@Success	204
//	@Failure	401	{object}	apperr.Error	"WIKI_LOCKED"
//	@Failure	404	{object}	apperr.Error	"PAGE_NOT_FOUND"
//	@Security	AgentToken
//	@Router		/wikis/{wikiId}/pages/{pageId} [delete]
func (h *Handler) deletePage(c *gin.Context) {
	if err := h.pages.Delete(c.Request.Context(), middleware.Wiki(c).ID, c.Param("pageId")); err != nil {
		middleware.Abort(c, err)
		return
	}
	c.Status(http.StatusNoContent)
}
