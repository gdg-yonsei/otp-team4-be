// updateWiki godoc
//
//	@Summary		위키 설정 변경
//	@Description	password: 생략하면 유지, ""이면 제거, 값이면 변경. 비밀번호가 바뀌면 기존 세션은 모두 무효화되고 요청자만 새 쿠키를 받는다.
//	@Tags			wikis
//	@Accept			json
//	@Produce		json
//	@Param			wikiId	path		string				true	"위키 ID (UUID)"
//	@Param			body	body		UpdateWikiRequest	true	"변경할 항목"
//	@Success		200		{object}	WikiResponse
//	@Failure		400		{object}	apperr.Error
//	@Failure		401		{object}	apperr.Error	"WIKI_LOCKED"
//	@Failure		404		{object}	apperr.Error	"WIKI_NOT_FOUND"
//	@Security		AgentToken
//	@Router			/wikis/{wikiId} [patch]
func (h *Handler) updateWiki(c *gin.Context) {
	var req UpdateWikiRequest
	if !bindJSON(c, &req) {
		return
	}
	w := middleware.Wiki(c)
	changed, err := h.wikis.Update(c.Request.Context(), w, service.UpdateWikiInput{Name: req.Name, Password: req.Password})
	if err != nil {
		middleware.Abort(c, err)
		return
	}
	// Changing the password revokes every session; keep the requester signed in.
	if changed && w.HasPassword() {
		token, exp, err := h.wikis.IssueSession(c.Request.Context(), w.ID)
		if err != nil {
			middleware.Abort(c, err)
			return
		}
		h.setSessionCookie(c, w.ID, token, exp)
	}
	c.JSON(http.StatusOK, h.wikiResp(w, true))
}

