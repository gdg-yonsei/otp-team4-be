// listPages godoc
//
//	@Summary	문서 목록
//	@Tags		pages
//	@Produce	json
//	@Param		wikiId		path		string	true	"위키 ID (UUID)"
//	@Param		category	query		string	false	"카테고리 필터"	Enums(PERSON, EVENT, INCIDENT, SCHEDULE, PLACE, GROUP, MEME, OTHER)
//	@Param		q			query		string	false	"제목 검색어"
//	@Success	200			{object}	PageListResponse
//	@Failure	400			{object}	apperr.Error
//	@Failure	401			{object}	apperr.Error	"WIKI_LOCKED"
//	@Security	AgentToken
//	@Router		/wikis/{wikiId}/pages [get]
func (h *Handler) listPages(c *gin.Context) {
	cat := model.PageCategory(c.Query("category"))
	if cat != "" && !cat.Valid() {
		middleware.Abort(c, apperr.BadRequest("알 수 없는 카테고리입니다: "+string(cat)))
		return
	}
	pages, err := h.pages.List(c.Request.Context(), middleware.Wiki(c).ID,
		service.PageFilter{Category: cat, Query: c.Query("q")})
	if err != nil {
		middleware.Abort(c, err)
		return
	}
	out := PageListResponse{Pages: make([]PageSummary, len(pages))}
	for i, p := range pages {
		out.Pages[i] = PageSummary{ID: p.ID, Title: p.Title, Category: p.Category}
	}
	c.JSON(http.StatusOK, out)
}

