// ---------- generations ----------

func toJobResponse(j *model.GenerationJob) JobResponse {
	nonNil := func(s []string) []string {
		if s == nil {
			return []string{}
		}
		return s
	}
	return JobResponse{
		JobID:          j.ID,
		Status:         j.Status,
		Mode:           j.Mode,
		CreatedPages:   len(j.CreatedPageIDs),
		UpdatedPages:   len(j.UpdatedPageIDs),
		CreatedPageIDs: nonNil(j.CreatedPageIDs),
		UpdatedPageIDs: nonNil(j.UpdatedPageIDs),
		Error:          j.Error,
		CreatedAt:      j.CreatedAt.UTC(),
		FinishedAt:     j.FinishedAt,
	}
}

